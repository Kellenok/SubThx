const NUMBER_LOCALE = { ru: "ru-RU", en: "en-US", ja: "ja-JP" };

export function setLang(choice) {
  const sys = (navigator.language || "ru").slice(0, 2);
  lang = choice && choice !== "auto" ? choice : DICTS[sys] ? sys : "en";
  dict = DICTS[lang];
  document.documentElement.lang = lang;
}

function fill(s, args) {
  return s.replace(/\{(\d)\}/g, (_, i) => args[i]);
}

/** t("key", ...args) */
export function t(key, ...args) {
  const v = dict[key] ?? ru[key] ?? key;
  return fill(Array.isArray(v) ? v[0] : v, args);
}

/** tn("cues", 5) -> "5 реплик" */
export function tn(key, n) {
  const forms = dict[key] ?? ru[key];
  let i = 0;
  if (forms.length > 1) {
    if (lang === "ru") {
      const m10 = n % 10,
        m100 = n % 100;
      i = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
    } else {
      i = n === 1 ? 0 : forms.length - 1;
    }
  }
  return forms[i].replace("{n}", fmtNum(n));
}

export function fmtNum(n, digits = 0) {
  return n.toLocaleString(NUMBER_LOCALE[lang], { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

export function fmtDuration(s) {
  if (s < 60) return t("sec", fmtNum(s, s < 10 ? 1 : 0));
  if (s < 3600) return s % 60 >= 1 && s < 600 ? t("minSec", Math.floor(s / 60), Math.round(s % 60)) : t("min", Math.round(s / 60));
  return t("hours", fmtNum(s / 3600, 1));
}

export function fmtDate(ms) {
  const d = new Date(ms);
  const today = new Date().toDateString() === d.toDateString();
  return today
    ? t("todayAt", d.toLocaleTimeString(NUMBER_LOCALE[lang], { hour: "2-digit", minute: "2-digit" }))
    : d.toLocaleDateString(NUMBER_LOCALE[lang], { day: "numeric", month: "short" });
}
